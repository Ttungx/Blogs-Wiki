/**
 * Post-build 脚本：在 Astro adapter 生成的 _worker.js 旁边创建 _entry.js，
 * 追加 UpdateWorkflow 类导出（workflows binding 的 class_name 要求）。
 *
 * 用法：astro build && node scripts/inject-worker-entry.js
 */

import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const serverDir = join(__dirname, '..', 'dist', 'server');
const indexPath = join(serverDir, 'entry.mjs');
const entryPath = join(serverDir, '_entry.mjs');

if (!existsSync(indexPath)) {
  console.error(`✗ Worker entry not found: ${indexPath}`);
  console.error('  Run "astro build" first.');
  process.exit(1);
}

writeFileSync(
  entryPath,
  [
    '// Auto-generated by scripts/inject-worker-entry.js',
    '// Re-exports Astro adapter handler + adds UpdateWorkflow class export.',
    "import original from './entry.mjs';",
    "export { UpdateWorkflow } from '../../worker/workflows/update-workflow';",
    'export default original;',
    '',
  ].join('\n'),
);

console.log(`✓ Workflow entry injected: ${entryPath}`);
