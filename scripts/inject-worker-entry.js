/**
 * Post-build 脚本：在 Astro adapter 生成的 entry.mjs 旁边创建 _entry.mjs，
 * 生成线上 Worker 入口。除 Astro 默认 fetch 外，把 scheduled 挂到 **default
 * export 对象**上：Cloudflare Module Worker 只认 `export default { scheduled }`，
 * 独立 `export async function scheduled` 会被运行时忽略并报
 * "Handler does not export a scheduled() function"。
 *
 * 用法：astro build && node scripts/inject-worker-entry.js
 */

import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const serverDir = join(__dirname, '..', 'dist', 'server');
const indexPath = join(serverDir, 'entry.mjs');
const entryPath = join(serverDir, '_entry.mjs');

/**
 * 生成 Worker 入口源码。scheduled 必须是 default export 的方法
 * （见 Cloudflare Workers scheduled handler 文档）。
 */
export function renderWorkerEntry() {
  return [
    '// Auto-generated by scripts/inject-worker-entry.js',
    '// Astro fetch + Cron scheduled on the default export (CF Module Worker).',
    "import original from './entry.mjs';",
    '',
    'const fetchHandler = typeof original === \'function\' ? original : original.fetch.bind(original);',
    '',
    '// 内容更新定时触发：只发一次 HTTP ping（网络等待不计 CPU）。',
    'async function scheduled(event, env, ctx) {',
    "  const base = (env.RUNNER_URL || '').trim();",
    "  const key = (env.CONTENT_SYNC_TOKEN || '').trim();",
    '  if (!base || !key) {',
    "    console.error('scheduled: RUNNER_URL / CONTENT_SYNC_TOKEN not configured; skip trigger');",
    '    return;',
    '  }',
    '  const target = `${base.replace(/\\/$/, \'\')}/run?key=${encodeURIComponent(key)}`;',
    '  ctx.waitUntil(',
    "    fetch(target, { method: 'POST', signal: AbortSignal.timeout(120_000) })",
    '      .then((res) => console.log(`scheduled ping -> HTTP ${res.status}`))',
    '      .catch((err) => console.error(`scheduled ping failed: ${err?.message ?? err}`))',
    '  );',
    '}',
    '',
    'export default {',
    '  fetch: fetchHandler,',
    '  scheduled,',
    '};',
    '',
  ].join('\n');
}

function main() {
  if (!existsSync(indexPath)) {
    console.error(`✗ Worker entry not found: ${indexPath}`);
    console.error('  Run "astro build" first.');
    process.exit(1);
  }

  writeFileSync(entryPath, renderWorkerEntry());
  console.log(`✓ Worker entry generated: ${entryPath} (fetch + scheduled on default export)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
